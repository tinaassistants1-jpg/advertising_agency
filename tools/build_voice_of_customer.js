function tr(x, o = {}) { return new TextRun({ text: x, size: 21, ...o }); }
function P(runs, o = {}) { return new Paragraph({ spacing: { after: 90 }, children: Array.isArray(runs) ? runs : [tr(runs)], ...o }); }
function H1(text) { return new Paragraph({ heading: HeadingLevel.HEADING_1, spacing: { before: 260, after: 90 }, children: [new TextRun({ text, bold: true, size: 26, color: DARK })] }); }
function insight(n, title, body, action) {
  return [
    new Paragraph({ spacing: { before: 200, after: 50 }, children: [new TextRun({ text: n + '. ' + title, bold: true, size: 23, color: ACCENT })] }),
    new Paragraph({ spacing: { after: 50 }, children: [tr(body)] }),
    new Paragraph({ spacing: { after: 120 }, children: [new TextRun({ text: '→ Что делаем: ', bold: true, size: 21, color: GREEN }), tr(action)] }),
  ];
}

