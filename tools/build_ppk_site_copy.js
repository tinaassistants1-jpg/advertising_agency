function tr(x, o = {}) { return new TextRun({ text: x, size: 22, ...o }); }
function P(runs, o = {}) {
  return new Paragraph({ spacing: { after: 100 }, children: Array.isArray(runs) ? runs : [tr(runs)], ...o });
}
function H1(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_1, spacing: { before: 280, after: 100 },
    children: [new TextRun({ text, bold: true, size: 28, color: DARK })] });
}
function block(label) {
  return new Paragraph({ spacing: { before: 220, after: 60 },
    children: [new TextRun({ text: label, bold: true, size: 20, color: 'FFFFFF' })],
    shading: { type: ShadingType.CLEAR, fill: ACCENT, color: 'auto' } });
}
function ph(text) {
  return new Paragraph({ spacing: { after: 100 },
    children: [new TextRun({ text: '[ПОДТВЕРДИТЬ: ' + text + ']', bold: true, size: 20, color: RED })] });
}
function copy(text) {
  return new Paragraph({ spacing: { after: 100 }, indent: { left: 300 },
    border: { left: { style: BorderStyle.SINGLE, size: 16, color: 'DDD3C7', space: 10 } },
    children: [tr(text)] });
}
function h(text) { // headline copy
  return new Paragraph({ spacing: { after: 60 }, indent: { left: 300 },
    children: [new TextRun({ text, bold: true, size: 26, color: DARK })] });
}
function bullet(text) {
  return new Paragraph({ numbering: { reference: 'b', level: 0 }, spacing: { after: 50 },
    indent: { left: 620, hanging: 260 }, children: [tr(text)] });
}

